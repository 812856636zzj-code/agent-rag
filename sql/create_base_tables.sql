-- Base tables for a fresh Oracle schema. Apply before the entity, relation,
-- and memory scripts. Existing schemas should use migrations instead.
CREATE TABLE RAG_DOCUMENTS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    FILE_NAME VARCHAR2(255),
    FILE_TYPE VARCHAR2(255),
    UPLOAD_TIME TIMESTAMP,
    STATUS VARCHAR2(255),
    DOCUMENT_TYPE VARCHAR2(255),
    CONTENT CLOB
);

CREATE TABLE RAG_DOCUMENT_CHUNKS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    DOCUMENT_ID NUMBER NOT NULL,
    CHUNK_INDEX NUMBER(10),
    CONTENT CLOB,
    TOKEN_COUNT NUMBER(10),
    EMBEDDING_STATUS VARCHAR2(255),
    CREATE_TIME TIMESTAMP,
    CONSTRAINT FK_RAG_CHUNK_DOCUMENT FOREIGN KEY (DOCUMENT_ID)
        REFERENCES RAG_DOCUMENTS (ID)
);

CREATE INDEX IDX_RAG_CHUNKS_DOC_ID ON RAG_DOCUMENT_CHUNKS (DOCUMENT_ID);

CREATE TABLE RAG_QUERY_LOGS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    QUESTION CLOB,
    ANSWER CLOB,
    SOURCE_DOC_ID NUMBER,
    RESPONSE_TIME_MS NUMBER(19),
    CREATE_TIME TIMESTAMP
);
