-- Additive Oracle migration for durable fixed-eval history.
-- Run once as the application schema owner. No existing tables are dropped.
WHENEVER SQLERROR EXIT SQL.SQLCODE

CREATE TABLE RAG_EVAL_RUNS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    RUN_STATUS VARCHAR2(20) NOT NULL,
    QUESTION_SET_SHA256 VARCHAR2(64) NOT NULL,
    STARTED_AT TIMESTAMP NOT NULL,
    COMPLETED_AT TIMESTAMP,
    CASE_COUNT NUMBER(10) NOT NULL,
    SUMMARY_JSON CLOB,
    ERROR_MESSAGE VARCHAR2(1000),
    CONSTRAINT CK_RAG_EVAL_RUN_STATUS
        CHECK (RUN_STATUS IN ('RUNNING', 'COMPLETED', 'FAILED')),
    CONSTRAINT CK_RAG_EVAL_CASE_COUNT CHECK (CASE_COUNT >= 0)
);

CREATE INDEX IDX_RAG_EVAL_RUNS_STARTED
    ON RAG_EVAL_RUNS (STARTED_AT);

CREATE TABLE RAG_EVAL_CASE_RESULTS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    RUN_ID NUMBER NOT NULL,
    CASE_POSITION NUMBER(10) NOT NULL,
    CASE_ID VARCHAR2(100) NOT NULL,
    RESULT_JSON CLOB NOT NULL,
    CONSTRAINT FK_RAG_EVAL_CASE_RUN
        FOREIGN KEY (RUN_ID) REFERENCES RAG_EVAL_RUNS (ID),
    CONSTRAINT UK_RAG_EVAL_CASE_POSITION UNIQUE (RUN_ID, CASE_POSITION),
    CONSTRAINT UK_RAG_EVAL_CASE_ID UNIQUE (RUN_ID, CASE_ID),
    CONSTRAINT CK_RAG_EVAL_CASE_POSITION CHECK (CASE_POSITION >= 0)
);

CREATE INDEX IDX_RAG_EVAL_CASE_RUN
    ON RAG_EVAL_CASE_RESULTS (RUN_ID);
